// Тексты ниши: свои на каждую нишу. Только общие знания об услуге – без названий компаний, цен, сроков и фактов о компаниях.
// Цифры («Кратко», таблица, номинации) страница собирает из данных сама – здесь их нет.
export interface NicheText {
  /** Ключ = адрес «категория/ниша», как в nishi.json: 'eda/kafe' */
  key: string;
  /** H1 страницы рейтинга: «Лучшие кафе Новосибирска – рейтинг 2026» */
  h1: string;
  /** <title> до 65 знаков: «Кафе Новосибирска: рейтинг 2026 по отзывам» */
  title: string;
  /** Как считать компании: [1, 2–4, 5+] – ['кафе','кафе','кафе'], ['клиника','клиники','клиник'] */
  unit: [string, string, string];
  /** Родительный падеж мн. ч. для фраз «рейтинг кафе», «рейтинг стоматологий» */
  rod: string;
  /** 1–2 строки для хаба категории: о чём рейтинг и что важно при выборе */
  short: string;
  /** Интро 2–3 предложения: что сравниваем и по чему выбирать в этой услуге */
  intro: string;
  /** Чек-лист 5–7 пунктов про ЭТУ услугу: заголовок пункта + 1–2 предложения */
  check: { t: string; d: string }[];
  /** FAQ 3–5 вопросов, которые реально задают про эту услугу в Новосибирске */
  faq: { q: string; a: string }[];
}
